// ─────────────────────────── playing poses ───────────────────────────
// In the reference the guitar hardly moves while the body sways and turns
// behind it, so the playing poses are built from layers:
//   body (with eyes) → guitar → hands / right leg.

/** Merge layers (later layers paint over earlier ones) into one frame at (0,0). */
function compose(...layers: SpriteFrame[]): SpriteFrame {
  const W = 40
  const H = 30
  const grid = Array.from({ length: H }, () => Array<string>(W).fill('.'))
  for (const l of layers)
    l.rows.forEach((row, r) =>
      [...row].forEach((ch, c) => {
        const y = l.dy + r
        const x = l.dx + c
        if (ch !== '.' && y >= 0 && y < H && x >= 0 && x < W) grid[y][x] = ch
      }),
    )
  return { dx: 0, dy: 0, rows: grid.map((r) => r.join('')) }
}

