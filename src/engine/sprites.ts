/** Side-on body block: left edge + bottom row shaded. `eyes` is painted on top. */
function body(dx: number, w: number, eyes: [number, number, string][], leg: number, legRows = 4): SpriteFrame {
  const rows: string[] = []
  for (let r = 0; r < 11; r++) {
    const edge = r < 9 ? 'o' : r === 9 ? 'oo' : '.o'
    rows.push((edge + 'O'.repeat(w - edge.length)).slice(0, w))
  }
  rows[10] = '.' + 'o'.repeat(w - 1)
  for (const [ex, ey, ch] of eyes) {
    const row = [...rows[ey]]
    row[ex] = ch
    rows[ey] = row.join('')
  }
  for (let r = 0; r < legRows; r++) rows.push(' '.repeat(leg).replace(/ /g, '.') + 'oO')
  return { dx, dy: 10, rows }
}

