/**
 * Pixel-art sprite frames for the guitar-playing Clawd.
 *
 * All frames share one canonical grid: sprite pixel (col,row) sits at
 * reference-px (SPRITE_ORIGIN.x + col*SPRITE_UNIT, SPRITE_ORIGIN.y + row*SPRITE_UNIT)
 * inside the 676x104 reference button. Frames were traced from the reference
 * recording (unit ≈ 2.9 source px) and cleaned up by hand.
 *
 * Palette keys:
 *   .  transparent        O  orange            o  orange shade
 *   E  eye                K  guitar black      k  guitar charcoal
 *   L  guitar lavender    l  lavender shadow   W  fret / highlight white
 */

